// Generates supabase/RESET_ALL.sql — a single paste-into-SQL-Editor script that
// wipes the public schema and replays migrations 001-010 (skipping 006, the
// old-taxonomy channel_fields seed, and stripping 001's old taxonomy seed).
// Regenerate after editing any migration:  node scripts/build-reset-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const mig = (f) => readFileSync(join(root, 'supabase', 'migrations', f), 'utf8')

const ORDER = [
  '001_initial_schema.sql',
  '002_phase2_schema.sql',
  '003_pending_slack_notifications.sql',
  '004_hubspot_tables.sql',
  '005_apply_phase2_and_3_idempotent.sql',
  // 006 skipped: seeds channel_fields for the RETIRED generic taxonomy
  '007_invites_and_pending_assignments.sql',
  '008_rls_hardening.sql',
  '009_saved_views.sql',
  '010_gtm_blueprint_extensions.sql',
  '011_lead_tracking.sql',
]

let m001 = mig('001_initial_schema.sql')
const seedMarker = '-- ============ SEED DATA: TAXONOMY ============'
const seedIdx = m001.indexOf(seedMarker)
if (seedIdx === -1) throw new Error('001 seed marker not found — file changed, update build-reset-sql.mjs')
m001 = m001.slice(0, seedIdx) + '-- (old taxonomy seed stripped — GTM blueprint is seeded by scripts/seed-gtm.mjs)\n'

const header = `-- ============================================================
-- RESET_ALL.sql  (GENERATED by scripts/build-reset-sql.mjs — do not hand-edit)
-- Full clean reset of the GSI Tracker database + replay of migrations
-- 001,002,003,004,005,007,008,009,010 (006 = old-taxonomy field seed, skipped).
--
-- Paste this ENTIRE file into Supabase Dashboard > SQL Editor > Run.
-- DESTRUCTIVE: drops every table in the public schema. Auth accounts
-- (auth.users) are preserved and re-mirrored at the end.
-- After this: run  node scripts/seed-gtm.mjs  to load the GTM blueprint.
-- ============================================================

-- ---------- TEARDOWN ----------
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP POLICY IF EXISTS "auth_upload"     ON storage.objects;
DROP POLICY IF EXISTS "auth_read_files" ON storage.objects;
DROP SCHEMA public CASCADE;
CREATE SCHEMA public;
COMMENT ON SCHEMA public IS 'standard public schema';
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL   ON SCHEMA public TO postgres, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES    TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON ROUTINES  TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
`

const footer = `
-- ---------- POST: re-mirror existing auth accounts ----------
-- handle_new_user only fires on INSERT into auth.users, so anyone who signed
-- in before this reset must be backfilled into public.users here.
INSERT INTO public.users (id, email, display_name, avatar_url, role)
SELECT id, email,
       COALESCE(raw_user_meta_data->>'full_name', split_part(email, '@', 1)),
       raw_user_meta_data->>'avatar_url',
       CASE WHEN email = 'kailash.gm@lyzr.ai' THEN 'admin'::user_role ELSE 'member'::user_role END
FROM auth.users
ON CONFLICT (id) DO NOTHING;

-- Belt-and-braces: make sure PostgREST roles can reach everything created above.
GRANT ALL ON ALL TABLES    IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES  IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- ---------- SANITY CHECK ----------
SELECT 'tables' AS what, count(*)::text AS value FROM information_schema.tables WHERE table_schema = 'public'
UNION ALL SELECT 'users mirrored', count(*)::text FROM public.users
UNION ALL SELECT 'categories (expect 0 until seed)', count(*)::text FROM categories
UNION ALL SELECT 'admin present', count(*)::text FROM public.users WHERE role = 'admin';
`

const banner = (f) => `\n-- ############################################################\n-- ${f}\n-- ############################################################\n`

let out = header
for (const f of ORDER) {
  out += banner(f) + (f === '001_initial_schema.sql' ? m001 : mig(f))
}
out += footer

writeFileSync(join(root, 'supabase', 'RESET_ALL.sql'), out)
console.log('wrote supabase/RESET_ALL.sql', out.length, 'bytes')
